def resolve(code):
    if code in ("az", "en", "tr", "ru"):
        return code
    env = os.environ.get("LANG", "")
    system_locale = locale.getlocale()[0] or ""
    detected = (env or system_locale).lower()
    if detected.startswith("tr"):
        return "tr"
    if detected.startswith("en"):
        return "en"
    if detected.startswith("ru"):
        return "ru"
    return "az"


def set_language(code):
    global _language
    _language = resolve(code)


def language():
    return _language


def t(text, **kwargs):
    catalog = {"az": AZ, "en": EN, "tr": TR, "ru": RU}.get(_language, AZ)
    translated = catalog.get(text, text)
    return translated.format(**kwargs) if kwargs else translated
